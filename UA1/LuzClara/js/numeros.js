//! numeros.js - Métodos de Math y Number
console.log(Math.round(4.6)); //* redondea: 5
console.log(Math.floor(4.6)); //* hacia abajo: 4
console.log(Math.ceil(4.2)); //* hacia arriba: 5
console.log(Math.max(45000, 75000, 38000)); //* el mayor
console.log(Math.min(45000, 75000, 38000)); //* el menor
console.log(Number.isInteger(2.75)); //* ¿es entero?
